CREATE DATABASE IF NOT EXISTS nova_market_eav_v3 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE nova_market_eav_v3;

DROP TABLE IF EXISTS valores_productos;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS atributos;
DROP TABLE IF EXISTS categorias;

CREATE TABLE categorias (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE productos (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    id_categoria INT UNSIGNED NOT NULL,
    precio DECIMAL(10,2) UNSIGNED NOT NULL,
    imagen VARCHAR(100) NOT NULL,
    FOREIGN KEY (id_categoria) REFERENCES categorias(id)
) ENGINE=InnoDB;
CREATE TABLE atributos (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE valores_productos (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    producto_id INT UNSIGNED NOT NULL,
    atributo_id INT UNSIGNED NOT NULL,
    valor VARCHAR(150) NOT NULL,
    FOREIGN KEY (producto_id) REFERENCES productos(id) ON DELETE CASCADE,
    FOREIGN KEY (atributo_id) REFERENCES atributos(id),
    UNIQUE (producto_id, atributo_id)
) ENGINE=InnoDB;

